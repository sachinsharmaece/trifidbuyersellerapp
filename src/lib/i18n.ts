export type DictionaryKey = keyof typeof dictionary;

/**
 * `vars` fills `{placeholder}` tokens (e.g. `step_of`'s `{current}`/`{total}`,
 * M5's `{count}`/`{qty}`/`{moq}`/`{rank}` and so on) — a plain string
 * replace, not a full ICU pluralisation engine, which this dictionary's
 * scale does not need yet.
 */
export function translate(
  locale: Locale,
  key: DictionaryKey,
  vars?: Record<string, string | number>,
): string {
  const entry = dictionary[key];
  const template = locale === 'hi' ? entry[1] : entry[0];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
